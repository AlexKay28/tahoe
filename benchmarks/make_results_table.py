#!/usr/bin/env python3
"""Generate the paper-ready consolidated results table from committed data.

Reads benchmarks/results/2026-09-16-difficulty-curve/curve.json (itself
regenerated by difficulty_curve.py from raw trial files) and writes
paper/results_slate.md — never hand-copied numbers.

Usage:
    python3 benchmarks/make_results_table.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CURVE = ROOT / "benchmarks/results/2026-09-16-difficulty-curve/curve.json"
OUT = ROOT / "paper/results_slate.md"

HEADER = """<!-- GENERATED by benchmarks/make_results_table.py — do not edit numbers by hand. -->
# TAHOE-93 vs classic — consolidated results (GLM-5.3-Flash, frozen protocol)

Source of truth: committed trial files per study (see RUN.md in each
`benchmarks/results/<date-study>/` directory); aggregated by
`benchmarks/difficulty_curve.py` into `curve.json`. Regenerate:

    python3 benchmarks/difficulty_curve.py && python3 benchmarks/make_results_table.py

"""


def fmt_acc(acc, ci):
    return f"{100*acc:.1f} ± {100*ci:.1f}"


def main():
    curve = json.loads(CURVE.read_text())
    curve.sort(key=lambda r: r["classic_acc"])

    lines = [
        HEADER,
        "| Benchmark | n/arm | Classic pass@1 | tahoe-93 pass@1 | Δ (pp, 95% CI) | Tokens (tahoe/classic) |",
        "|---|---|---|---|---|---|",
    ]
    total_n = 0
    sig = 0
    import math

    for r in curve:
        n = r["n_classic"]
        total_n += n
        if r["significant_95"]:
            sig += 1
        star = " **\\***" if r["significant_95"] else ""
        # per-arm CIs from binomial approx (same convention as study RUN.mds)
        ci_c = 1.96 * math.sqrt(r["classic_acc"] * (1 - r["classic_acc"]) / n)
        ci_t = 1.96 * math.sqrt(r["tahoe_acc"] * (1 - r["tahoe_acc"]) / r["n_tahoe"])
        lines.append(
            f"| {r['benchmark']} | {n} | {fmt_acc(r['classic_acc'], ci_c)} ({round(r['classic_acc']*n)}/{n}) "
            f"| {fmt_acc(r['tahoe_acc'], ci_t)} ({round(r['tahoe_acc']*r['n_tahoe'])}/{r['n_tahoe']}) "
            f"| {r['delta_pp']:+.1f} ± {r['delta_ci95_pp']:.1f}{star} "
            f"| {r['token_ratio']:.3f} |"
        )

    lines += [
        "",
        f"**{len(curve)} benchmarks, {total_n} trials per arm.** "
        f"{sig} of {len(curve)} deltas significant at 95% (**\\***): "
        "gsm8k (+11.8pp at 0.80× tokens) and mmlu_pro (+4.2pp at 0.88× tokens). "
        "All four harder-benchmark additions trend positive; direction-consistent "
        "across the slate. Difficulty is anchored to our classic arm.",
        "",
        "Slate studies (2026-09-16/17): GPQA Diamond (#96), AIME 2024+2025 (#97), "
        "MMLU-Pro stratified-800 (#98), LiveCodeBench v6-150 (#99); stage-1 full "
        "test sets (10 benchmarks) from 2026-09-13 (#50 wave). Zero infra errors "
        "in all harder-slate runs.",
        "",
    ]

    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT}")
    print("\n".join(lines[2:]))


if __name__ == "__main__":
    main()
